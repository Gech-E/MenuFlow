import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import test from "node:test";
import { asActor, bootDatabase, createUser } from "./postgres.mjs";

test("two restaurants and two diners order, serve and settle on PostgreSQL", async t => {
  const db = await bootDatabase();
  t.after(() => db.stop());
  const { pool } = db;
  const owner = await createUser(pool, "owner@example.test");
  const otherOwner = await createUser(pool, "another@example.test");
  const cashier = await createUser(pool, "cashier@example.test");
  const onboard = user => asActor(pool,user,async c =>
    (await c.query("select public.mf_onboard('Test café','Main') ctx")).rows[0].ctx.branches[0]);
  const { id: branchId, restaurantId } = await onboard(owner);
  const otherBranch = await onboard(otherOwner);
  const scope = { restaurantId, branchId };
  await pool.query("update branches set tax_bps=1500,service_bps=500 where id=$1",[branchId]);
  await pool.query("insert into staff_branch_roles(restaurant_id,branch_id,user_id,roles) values($1,$2,$3,array['CASHIER'])",[restaurantId,branchId,cashier]);
  const tab = (await pool.query("insert into dining_tables(restaurant_id,branch_id,label,table_number) values($1,$2,'Courtyard',8) returning *",[restaurantId,branchId])).rows[0];
  const cat = (await pool.query("insert into menu_categories(restaurant_id,branch_id,name) values($1,$2,'Beverages') returning id",[restaurantId,branchId])).rows[0];
  const variants = JSON.stringify([{id:"large", name:"Large", priceMinor:1200}]);
  const modifiers = JSON.stringify([{id:"milk",name:"Milk",min:1,max:1,options:[{id:"oat",name:"Oat milk",priceMinor:100}]}]);
  const item = (await pool.query("insert into menu_items(restaurant_id,branch_id,category_id,name,category,price,published,variants,modifier_groups) values($1,$2,$3,'Coffee','Beverages',10.00,true,$4,$5) returning id",[restaurantId,branchId,cat.id,variants,modifiers])).rows[0];
  const rpc = (user, action, body={}, device=null) => asActor(pool,user,async c =>
    (await c.query("select public.mf_operations($1,$2::jsonb,$3) result",[action,JSON.stringify(body),device])).rows[0].result);
  const staff = (action, body={}) => rpc(owner,action,{...scope,...body});
  const host = randomBytes(32).toString("base64url");
  const diner = randomBytes(32).toString("base64url");
  const guest = (action, body={}, device=host) => rpc(null,action,body,device);
  const lines = [{itemId:item.id,quantity:2,variantId:"large",optionIds:["oat"],note:"Less foam"}];
  let sessionId, order, frozen, receipt;
  await t.test("concurrent opening yields one session; QR alone grants no access", async () => {
    const races = await Promise.allSettled([staff("open",{tableId:tab.id}),staff("open",{tableId:tab.id})]);
    const won = races.filter(x=>x.status==="fulfilled");
    assert.equal(won.length,1);
    const invitation = won[0].value;
    sessionId = invitation.sessionId;
    assert.equal((await guest("guestState")).session,null);
    assert.equal((await guest("join",{locator:tab.qr_locator, code:"BAD"})).admissionError,true);
    const replacement = await staff("issueCode",{sessionId,host:true});
    assert.equal((await guest("join",{locator:tab.qr_locator,code:invitation.code})).admissionError,true);
    await guest("join",{locator:tab.qr_locator,code:replacement.code});
    assert.equal((await guest("join",{locator:tab.qr_locator,code:replacement.code},diner)).admissionError,true);
    const guestInvite = await staff("issueCode",{sessionId});
    await guest("join",{locator:tab.qr_locator,code:guestInvite.code},diner);
    assert.equal((await guest("guestState")).session.is_host,true);
    assert.equal((await guest("guestState",{},diner)).session.is_host,false);
    await assert.rejects(pool.query("update dining_tables set active=false where id=$1",[tab.id]),/Close active/);
    await assert.rejects(rpc(otherOwner,"staffState",scope));
    await assert.rejects(staff("staffState",{branchId:otherBranch.id}));
    await assert.rejects(rpc(null,"staffState",scope));
  });
  await t.test("quote validates catalog selections; repeated order commits once",async()=>{
    await assert.rejects(guest("quote",{items:[{itemId:item.id,quantity:1}]}),/required modifiers/);
    await assert.rejects(guest("quote",{items:[{...lines[0],optionIds:["invalid"]}]}));
    await assert.rejects(guest("quote",{items:[{...lines[0],quantity:0}]}));
    const quote = await guest("quote",{items:lines});
    assert.equal(quote.subtotal_minor,"2600");
    await pool.query("update menu_items set version=version+1 where id=$1",[item.id]);
    await assert.rejects(guest("order",{items:lines,quoteHash:quote.quote_hash,key:randomUUID()}),e=>e.code==="40001");
    const current = await guest("quote",{items:lines});
    const body = {items:lines,quoteHash:current.quote_hash,key:randomUUID(),note:"Together please"};
    const orders = await Promise.all([guest("order",body),guest("order",body)]);
    assert.deepEqual(orders[0],orders[1]);
    order = orders[0].id;
    await assert.rejects(guest("order",{...body,note:"different"}),e=>e.code==="40001");
    const state = await guest("guestState");
    assert.equal(state.orders.length,1);
    assert.equal(state.orders[0].items[0].selection.options[0].name,"Oat milk");
    assert.equal(state.orders[0].items[0].unit_minor,"1300");
    assert.equal(state.bill.tip_minor,"0");
    const second = await guest("guestState",{},diner);
    assert.equal(second.orders.length,0);
    assert.equal(second.bill,null);
    await assert.rejects(guest("cancel",{orderId:order},diner));
    await assert.rejects(guest("checkout",{version:state.bill.version,tipPercent:10},diner),e=>e.code==="42501");
    await assert.rejects(guest("checkout",{version:state.bill.version,tipPercent:10}),/served/);
    await assert.rejects(rpc(otherOwner,"transition",{...scope,orderId:order,status:"accepted"}));
    await assert.rejects(rpc(cashier,"transition",{...scope,orderId:order,status:"accepted"}),e=>e.code==="42501");
    const request = await guest("request",{category:"water"});
    assert.deepEqual(await guest("request",{category:"water"}),request);
    await staff("requestStatus",{id:request.id,status:"acknowledged"});
    await staff("requestStatus",{id:request.id,status:"completed"});
    assert.equal((await guest("guestState")).requests[0].status,"completed");
  });
  await t.test("fulfillment, discount allocation, optional tip and invoice revisions reconcile",async()=>{
    await assert.rejects(staff("transition",{orderId:order,status:"served"}),e=>e.code==="40001");
    for (const status of ["accepted","preparing","ready","served"]) {
      await staff("transition",{orderId:order,status});
    }
    await assert.rejects(guest("cancel",{orderId:order}));
    await staff("discount",{sessionId,amountMinor:"101",reason:"Service adjustment"});
    const bill = (await guest("guestState")).bill;
    assert.equal(bill.eligible_minor,"2499");
    assert.equal(bill.tax_minor,"375");
    assert.equal(bill.service_minor,"125");
    assert.equal(bill.total_minor,"2999");
    const first = await guest("checkout",{version:bill.version,tipPercent:0});
    await assert.rejects(guest("quote",{items:lines}),e=>e.code==="40001");
    frozen = await guest("checkout",{version:first.version,tipPercent:10});
    assert.equal(frozen.tip_minor,"250");
    assert.equal(frozen.total_minor,"3249");
    await assert.rejects(staff("settle",{sessionId,version:first.version,tenderMinor:"4000",key:randomUUID()}),e=>e.code==="40001");
    await assert.rejects(staff("settle",{sessionId,version:frozen.version,tenderMinor:"3000",key:randomUUID()}),/cash/);
    await pool.query("update menu_items set name='New name',price=100 where id=$1",[item.id]);
    assert.equal((await guest("guestState")).bill.total_minor,"3249");
  });
  await t.test("concurrent cash settlement, receipt reprint, metrics and tenancy",async()=>{
    const pay = {sessionId,version:frozen.version,tenderMinor:"4000",key:randomUUID()};
    const replay = await Promise.all([staff("settle",pay),staff("settle",pay)]);
    assert.deepEqual(replay[0],replay[1]);
    receipt = replay[0];
    assert.equal(receipt.change_minor,"751");
    assert.equal(receipt.snapshot.lines[0].name,"Coffee");
    await assert.rejects(staff("settle",{...pay,key:randomUUID()}),e=>e.code==="40001");
    assert.equal((await pool.query("select count(*) qty from cash_payments")).rows[0].qty,"1");
    assert.equal((await guest("guestState")).receipt.id,receipt.id);
    assert.equal((await guest("guestState")).orders[0].status,"completed");
    assert.equal((await guest("guestState",{},diner)).receipt,null);
    const stats = await staff("staffState");
    assert.equal(stats.payments.length,1);
    assert.equal(stats.metrics.revenue_minor,"2499");
    assert.equal(stats.metrics.tips_minor,"250");
    assert.equal(stats.metrics.best_sellers[0].quantity,2);
    assert.equal(stats.metrics.active_tables,0);
    assert.equal((await rpc(cashier,"staffState",scope)).metrics,null);
    await assert.rejects(asActor(pool,cashier,c=>c.query("delete from dining_receipts")),e=>e.code==="42501");
    const fresh=await staff("open",{tableId:tab.id});
    assert.notEqual(fresh.sessionId,sessionId);
    await assert.rejects(guest("quote",{items:lines}),e=>e.code==="40001");
    await staff("void",{sessionId:fresh.sessionId});
    await pool.query("update dining_sessions set closed_at=now()-interval '25 hours' where id=$1",[sessionId]);
    const expired = await guest("guestState");
    assert.deepEqual(expired,{session:null,orders:[],requests:[],bill:null,receipt:null});
  });
});
